const CLI = join(import.meta.dirname, '..', 'src', 'cli.mjs');
const run = (cmd, options = {}) => execSync(`node ${CLI} ${cmd}`, { encoding: 'utf-8', timeout: 15000, ...options });
const runWithHome = (cmd, home, options = {}) => run(cmd, {
  ...options,
  env: { ...process.env, HOME: home },
});

